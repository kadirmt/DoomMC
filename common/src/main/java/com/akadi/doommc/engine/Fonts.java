	private Fonts() {
	}

	public static int width(String text, int scale) {
		return text.length() * (GW + 1) * scale;
	}

	public static void draw(int[] fb, int fbW, int fbH, String text, int x, int y, int color, int scale) {
		int cx = x;
		for (int i = 0; i < text.length(); i++) {
			String[] gl = GLYPHS.get(Character.toUpperCase(text.charAt(i)));
			if (gl != null) {
				for (int gy = 0; gy < GH; gy++) {
					String row = gl[gy];
					for (int gx = 0; gx < GW; gx++) {
						if (row.charAt(gx) != '#') continue;
						for (int sy = 0; sy < scale; sy++) {
							int py = y + gy * scale + sy;
							if (py < 0 || py >= fbH) continue;
							for (int sx = 0; sx < scale; sx++) {
								int pxx = cx + gx * scale + sx;
								if (pxx < 0 || pxx >= fbW) continue;
								fb[py * fbW + pxx] = color;
							}
						}
					}
				}
			}
			cx += (GW + 1) * scale;
		}
	}

	/** Same as draw() but with a one-pixel-ish drop shadow, for readability over busy scenes. */
	public static void drawShadow(int[] fb, int fbW, int fbH, String text, int x, int y, int color, int scale) {
		draw(fb, fbW, fbH, text, x + scale, y + scale, 0xFF000000, scale);
		draw(fb, fbW, fbH, text, x, y, color, scale);
	}

	public static void drawCentered(int[] fb, int fbW, int fbH, String text, int y, int color, int scale) {
		drawShadow(fb, fbW, fbH, text, (fbW - width(text, scale)) / 2, y, color, scale);
	}
